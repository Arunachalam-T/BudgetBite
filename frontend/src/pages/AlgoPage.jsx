import { useState } from 'react'
import { useApp } from '../AppContext'
import { Play, AlertCircle, ChevronDown, ChevronUp } from 'lucide-react'
import BenchmarkCharts from '../charts/BenchmarkCharts'

const STATUS_BADGE = {
  'Optimal':                    'badge-green',
  'Feasible (not proven optimal)': 'badge-yellow',
  'No feasible solution found': 'badge-red',
  'Infeasible':                 'badge-red',
  'Interrupted':                'badge-grey',
}

const ALGO_EXPLANATIONS = {
  'Brute Force': {
    how: 'Exhaustively enumerates every possible assignment of recipes to meal slots without any pruning.',
    space: 'Explores the entire search space: O(|R|^(7×m)) where |R| is recipe count and m is meals/day.',
    pruning: 'None — every combination is evaluated.',
    complexity: 'Time: O(|R|^(7m)), Space: O(7m)',
    performance: 'Provides a guaranteed optimum when exhausted, but becomes impractical for large datasets.',
  },
  'Greedy': {
    how: 'Makes a locally optimal choice at each meal slot based on the active optimization mode.',
    space: 'Processes one slot at a time; no backtracking.',
    pruning: 'Not applicable — greedy does not explore multiple branches.',
    complexity: 'Time: O(7m × |R|), Space: O(7m)',
    performance: 'Very fast but cannot guarantee global optimality. May miss the overall best solution.',
  },
  'Dynamic Programming': {
    how: 'Solves the problem recursively and memoizes states to avoid recomputing the same (slot, repetitions, nutrition) combinations.',
    space: 'Builds a state-space map keyed by slot index, recipe repetition counts, and rounded per-day nutrition values.',
    pruning: 'Memoized states are not re-explored; infeasible extensions are skipped.',
    complexity: 'Time: O(states × |R|), Space: O(states)',
    performance: 'Exact when all states are explored; interrupted results are best-feasible. State space can be large.',
  },
  'Backtracking': {
    how: 'Recursively assigns recipes slot by slot, undoing choices that violate constraints.',
    space: 'Explores a depth-first search tree with safe pruning of infeasible branches.',
    pruning: 'Prunes when: repetition limit exceeded, fat limit already exceeded, or other hard constraints already violated.',
    complexity: 'Time: O(|R|^(7m)) worst case, much less with pruning; Space: O(7m)',
    performance: 'Often faster than Brute Force due to pruning. Exact and proves optimality when exhausted.',
  },
  'Branch and Bound': {
    how: 'Maintains a priority queue of partial plans ordered by their optimistic objective bound, expanding the most promising node first.',
    space: 'Nodes hold partial plans with accumulated state and a valid optimistic bound.',
    pruning: 'A node is pruned when its optimistic bound cannot improve upon the current incumbent.',
    complexity: 'Time: depends on bound quality; Space: O(queue size)',
    performance: 'Can prove optimality when the queue is exhausted. Reports an optimality gap if interrupted.',
  },
}

function AlgoExplanation({ name }) {
  const [open, setOpen] = useState(false)
  const info = ALGO_EXPLANATIONS[name]
  if (!info) return null
  return (
    <div style={{ marginTop: 8 }}>
      <button
        onClick={() => setOpen(o => !o)}
        style={{ display: 'flex', alignItems: 'center', gap: 6, fontSize: 12, color: 'var(--color-primary)', background: 'none', border: 'none', cursor: 'pointer', fontWeight: 600 }}
      >
        {open ? <ChevronUp size={14} /> : <ChevronDown size={14} />} How it works
      </button>
      {open && (
        <div style={{ marginTop: 8, fontSize: 12, color: 'var(--color-text-muted)', lineHeight: 1.6, background: 'var(--color-surface-2)', padding: '12px 16px', borderRadius: 'var(--radius-sm)' }}>
          <p><strong>Approach:</strong> {info.how}</p>
          <p style={{ marginTop: 6 }}><strong>Pruning:</strong> {info.pruning}</p>
          <p style={{ marginTop: 6 }}><strong>Complexity:</strong> {info.complexity}</p>
          <p style={{ marginTop: 6 }}><strong>When to expect this performance:</strong> {info.performance}</p>
        </div>
      )}
    </div>
  )
}

function BacktrackingPlan({ benchResult }) {
  if (!benchResult) return null
  const bt = benchResult.results?.find(r => r.algorithm_name === 'Backtracking')
  if (!bt) return null

  const DAY_NAMES = ['Monday','Tuesday','Wednesday','Thursday','Friday','Saturday','Sunday']
  const byDay = {}
  for (let d = 0; d < 7; ++d) byDay[d] = []
  ;(bt.plan || []).forEach(a => { if (byDay[a.day] !== undefined) byDay[a.day].push(a) })

  return (
    <div className="card" style={{ marginTop: 24 }}>
      <div className="card-title">Meal Plan Generated by Backtracking</div>
      {bt.is_feasible ? (
        <>
          <div style={{ display: 'flex', gap: 20, flexWrap: 'wrap', fontSize: 13, marginBottom: 16 }}>
            <span>Purchase cost: <strong>₹{bt.evaluation?.weekly_purchase_cost?.toFixed(0)}</strong></span>
            <span>Nutrition deviation: <strong>{(bt.evaluation?.nutrition_deviation_score*100)?.toFixed(1)}%</strong></span>
            <span>Distinct recipes: <strong>{bt.evaluation?.distinct_recipe_count}</strong></span>
            <span className={`badge ${STATUS_BADGE[bt.status] || 'badge-grey'}`}>{bt.status}</span>
          </div>
          <div className="day-grid">
            {Array.from({length:7},(_,d) => (
              <div key={d} className="day-card">
                <div className="day-header">{DAY_NAMES[d]}</div>
                {byDay[d].map((a,i) => (
                  <div key={i} className="meal-slot">
                    <div className="meal-slot-type">{a.meal_type}</div>
                    <div className="meal-slot-name" style={{ fontSize: 11 }}>{a.recipe_id}</div>
                  </div>
                ))}
              </div>
            ))}
          </div>
        </>
      ) : (
        <div className="alert alert-error">
          <AlertCircle size={16} />
          <div>
            <strong>Backtracking did not find a feasible plan.</strong>
            <p>{bt.status}: {bt.termination_reason}</p>
          </div>
        </div>
      )}
    </div>
  )
}

export default function AlgoPage() {
  const { dataset, config, benchmark, runBenchmark, loading, error, activeMode, setActiveMode } = useApp()
  const [mode, setMode] = useState(activeMode || 'Nutrition')

  const isLoading = loading?.benchmark
  const benchError = error?.benchmark

  const handleModeChange = (newMode) => {
    setMode(newMode)
    if (setActiveMode) setActiveMode(newMode)
  }

  return (
    <div>
      <h2 className="section-title">Algorithm Comparison</h2>
      <p className="section-sub">Compare all five algorithms on the same dataset and configuration</p>

      {/* Control bar */}
      <div className="card" style={{ marginBottom: 20, display: 'flex', gap: 16, alignItems: 'center', flexWrap: 'wrap' }}>
        <div>
          <div style={{ fontSize: 12, fontWeight: 600, marginBottom: 4 }}>Optimization Mode</div>
          <div style={{ display: 'flex', gap: 6 }}>
            {['Nutrition', 'Budget'].map(m => (
              <button
                key={m}
                onClick={() => handleModeChange(m)}
                className={`btn btn-sm ${mode === m ? 'btn-primary' : 'btn-outline'}`}
              >
                {m}
              </button>
            ))}
          </div>
        </div>
        <div style={{ flex: 1 }} />
        <button
          className="btn btn-primary"
          disabled={!dataset?.is_valid || isLoading}
          onClick={() => runBenchmark(mode)}
        >
          {isLoading
            ? <><span className="spinner" style={{ width: 14, height: 14 }} /> Running all algorithms…</>
            : <><Play size={14} /> Run All Algorithms ({mode})</>}
        </button>
      </div>

      {benchError && <div className="alert alert-error"><AlertCircle size={16} /> {benchError}</div>}

      {!benchmark ? (
        <div className="empty-state">
          <Play size={36} style={{ color: 'var(--color-text-muted)' }} />
          <h3>No benchmark results yet</h3>
          <p>Click "Run All Algorithms" to compare all five algorithms.</p>
        </div>
      ) : (
        <>
          {/* Comparison table */}
          <div className="card" style={{ marginBottom: 20 }}>
            <div className="card-title">Algorithm Comparison Table</div>
            <div className="table-wrap">
              <table>
                <thead>
                  <tr>
                    <th>Algorithm</th>
                    <th style={{ textAlign: 'right' }}>Time (ms)</th>
                    <th style={{ textAlign: 'right' }}>Nodes</th>
                    <th style={{ textAlign: 'right' }}>Pruned</th>
                    <th style={{ textAlign: 'right' }}>Memory (KB)</th>
                    <th style={{ textAlign: 'right' }}>Objective</th>
                    <th>Status</th>
                    <th>Gap %</th>
                  </tr>
                </thead>
                <tbody>
                  {benchmark.results?.map((r, i) => (
                    <tr key={i}>
                      <td><strong>{r.algorithm_name}</strong></td>
                      <td style={{ textAlign: 'right' }}>{r.execution_time_ms?.toFixed(1)}</td>
                      <td style={{ textAlign: 'right' }}>{r.nodes_explored?.toLocaleString()}</td>
                      <td style={{ textAlign: 'right' }}>{r.branches_pruned?.toLocaleString()}</td>
                      <td style={{ textAlign: 'right' }}>{r.peak_memory_bytes ? (r.peak_memory_bytes/1024).toFixed(0) : '—'}</td>
                      <td style={{ textAlign: 'right' }}>
                        {r.is_feasible ? r.primary_objective?.toFixed(3) : '—'}
                      </td>
                      <td>
                        <span className={`badge ${STATUS_BADGE[r.status] || 'badge-grey'}`}>
                          {r.status}
                        </span>
                      </td>
                      <td>
                        {r.optimality_gap_pct >= 0 ? `${r.optimality_gap_pct?.toFixed(2)}%` : '—'}
                      </td>
                    </tr>
                  ))}
                </tbody>
              </table>
            </div>
          </div>

          {/* Charts */}
          <BenchmarkCharts results={benchmark.results} mode={mode} />

          {/* Backtracking plan */}
          <BacktrackingPlan benchResult={benchmark} />

          {/* Algorithm explanations */}
          <div className="card" style={{ marginTop: 24 }}>
            <div className="card-title">Algorithm Explanations</div>
            {benchmark.results?.map((r, i) => (
              <div key={i} style={{ marginBottom: i < benchmark.results.length - 1 ? 16 : 0, paddingBottom: 16, borderBottom: i < benchmark.results.length - 1 ? '1px solid var(--color-border)' : 'none' }}>
                <div style={{ fontWeight: 700, fontSize: 14 }}>{r.algorithm_name}</div>
                <AlgoExplanation name={r.algorithm_name} />
              </div>
            ))}
          </div>
        </>
      )}
    </div>
  )
}

